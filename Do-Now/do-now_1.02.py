# Variables

# What is a variable?
# Basically: a name that refers to a value
# All variables are assigned values
# Examples:
	# n = 17
	# pi = 3.1315926535897932
	# message = 'And now for something completely different'
# Question: what part of the examples are the variables? the assignments?

# Variable Rules
# What is allowed:
# -letters
# -numbers
# -some punctuation
# -can be any length

# What isn't allowed:
# -first character cannot be a number
# -keywords (such as print)
# -duplicate names (causes reassignment)

